import { redirect } from 'next/navigation';
import { getAdminAccess } from '@admin/lib/access';
import { isLocale } from '@admin/lib/i18n';
import { logoutAction } from '@admin/app/[locale]/login/actions';
import { CodeField } from '../code-field';
import { mfaCopy } from '../copy';
import { enrollMfaAction } from '../actions';

export default async function EnrollMfaPage({
  params,
  searchParams,
}: {
  params: Promise<{ locale: string }>;
  searchParams: Promise<{ error?: string }>;
}) {
  const { locale: rawLocale } = await params;
  if (!isLocale(rawLocale)) redirect('/ar/login');
  const locale = rawLocale;
  const access = await getAdminAccess();
  if (access.status === 'ok') redirect(`/${locale}/admin`);
  if (access.status === 'mfa-verify') redirect(`/${locale}/mfa/verify`);
  if (access.status !== 'mfa-enroll') redirect(`/${locale}/login`);

  const copy = mfaCopy[locale];
  const { error } = await searchParams;
  const { db } = access.actor;

  // Drop abandoned, never-verified factors so only the one shown below can be confirmed.
  const { data: existing } = await db.auth.mfa.listFactors();
  for (const factor of existing?.all ?? []) {
    if (factor.factor_type === 'totp' && factor.status === 'unverified') {
      await db.auth.mfa.unenroll({ factorId: factor.id });
    }
  }
  const { data, error: enrollError } = await db.auth.mfa.enroll({
    factorType: 'totp',
    friendlyName: `DarSak admin ${new Date().toISOString().slice(0, 10)}`,
  });
  // The QR is an SVG data URL generated by Supabase, never user input; still insist on that exact shape.
  const qr = data?.totp.qr_code;
  const qrSrc = qr?.startsWith('data:image/svg+xml') ? qr : null;
  const secret = data?.totp.secret;

  return (
    <main className="container flex min-h-screen items-center justify-center py-12">
      <section className="w-full max-w-lg rounded-2xl border border-line bg-surface p-7 shadow-xl sm:p-10">
        <p className="text-xs font-bold uppercase tracking-[.15em] text-orange">{copy.brand}</p>
        <h1 className="mt-3 text-3xl font-black text-teal">{copy.enrollTitle}</h1>
        <p className="mt-3 leading-7 text-muted">{copy.enrollIntro}</p>
        <ol className="mt-4 list-decimal space-y-1 ps-5 text-sm leading-6 text-ink-soft">
          {copy.steps.map(step => (
            <li key={step}>{step}</li>
          ))}
        </ol>
        {(error || enrollError || !data || !qrSrc || !secret) && (
          <p
            className="mt-5 rounded-xl bg-[#f3e1db] p-3 text-sm leading-6 text-[#6e2414]"
            role="alert"
          >
            {error === 'code' && data ? copy.badCodeEnroll : copy.unavailable}
          </p>
        )}
        {data && qrSrc && secret && (
          <>
            <div className="mt-6 flex justify-center rounded-xl border border-line bg-white p-3">
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img src={qrSrc} alt={copy.qrAlt} width={200} height={200} />
            </div>
            <p className="mt-4 text-sm font-bold">{copy.secret}</p>
            <code
              dir="ltr"
              className="mt-1 block select-all break-all rounded-lg bg-cream px-3 py-3 text-center font-mono text-sm"
            >
              {secret}
            </code>
            <form action={enrollMfaAction} className="mt-6 grid gap-4">
              <input type="hidden" name="locale" value={locale} />
              <input type="hidden" name="factorId" value={data.id} />
              <CodeField label={copy.code} />
              <button
                className="min-h-11 rounded-lg bg-teal px-4 py-3 font-bold text-white focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-teal"
                type="submit"
              >
                {copy.submitEnroll}
              </button>
            </form>
          </>
        )}
        <form action={logoutAction} className="mt-5">
          <input type="hidden" name="locale" value={locale} />
          <button
            type="submit"
            className="min-h-11 rounded-lg px-3 text-sm font-bold text-orange hover:bg-cream focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-teal"
          >
            {copy.logout}
          </button>
        </form>
      </section>
    </main>
  );
}
